#!/usr/bin/env python3
"""Generate frontend/js/wilayah.js from the branch-`ken` PostgreSQL tables.

This removes the last copy of the old mockup's 23-entry dummy WILAYAH. The
generated module contains the full hierarchy from provinsi -> kota ->
kecamatan -> kelurahan (83,762 kelurahan in the imported ken dump).

Usage:
    python3 tools/generate_wilayah.py

Run it again after re-importing the ken dump (tools/import_ken_sql.py).
"""
from __future__ import annotations

import hashlib
import json
import os
from pathlib import Path

import psycopg2

ROOT = Path(__file__).resolve().parent.parent
OUTPUT = ROOT / "frontend" / "js" / "wilayah.js"
DSN = os.getenv(
    "APPB_DB_DSN",
    "dbname=appb_db user=appb password=appb_pass host=127.0.0.1 port=5432",
)


def main() -> None:
    conn = psycopg2.connect(DSN)
    try:
        with conn.cursor() as cur:
            cur.execute("""
                SELECT p.id_provinsi, p.nama_provinsi,
                       kt.id_kota, kt.nama_kota,
                       kc.id_kecamatan, kc.nama_kecamatan,
                       k.id_kelurahan, k.nama_kelurahan
                FROM kelurahan k
                JOIN kecamatan kc ON kc.id_kecamatan = k.id_kecamatan
                JOIN kota kt ON kt.id_kota = kc.id_kota
                JOIN provinsi p ON p.id_provinsi = kt.id_provinsi
                ORDER BY p.id_provinsi, kt.id_kota, kc.id_kecamatan, k.id_kelurahan
            """)
            rows = cur.fetchall()
    finally:
        conn.close()

    wilayah: dict[str, dict[str, dict[str, list[str]]]] = {}
    positions: dict[str, dict[str, dict[str, str]]] = {}
    for id_prov, prov, id_kota, kab, id_kec, kec, _id_kel, kel in rows:
        kota = wilayah.setdefault(prov, {}).setdefault(kab, {})
        kota.setdefault(kec, []).append(kel)
        positions.setdefault(prov, {}).setdefault(kab, {})["id"] = id_kota

    # Peta statis di UI memakai viewBox "140 60 420 200". Posisi pin dibuat
    # deterministik dari id_kota supaya tidak ada data dummy KAB_POS.
    kab_pos: dict[str, list[int]] = {}
    for by_prov in positions.values():
        for kab, info in by_prov.items():
            digest = hashlib.sha256(info["id"].encode("utf-8")).digest()
            kab_pos[kab] = [
                165 + int.from_bytes(digest[0:2], "big") % 370,
                75 + int.from_bytes(digest[2:4], "big") % 170,
            ]

    counts = (
        len(wilayah),
        sum(len(kabs) for kabs in wilayah.values()),
        sum(len(kecs) for kabs in wilayah.values() for kecs in kabs.values()),
        len(rows),
    )
    header = (
        "// GENERATED by tools/generate_wilayah.py — jangan diedit manual.\n"
        f"// Sumber: PostgreSQL appb_db, dump branch `ken` "
        f"({counts[0]} provinsi, {counts[1]} kabupaten/kota, "
        f"{counts[2]} kecamatan, {counts[3]} kelurahan).\n"
        "// Jalankan ulang setelah tools/import_ken_sql.py.\n"
    )
    body = (
        "export const WILAYAH = "
        + json.dumps(wilayah, ensure_ascii=False, separators=(",", ":"))
        + ";\n"
        "export const KAB_POS = "
        + json.dumps(kab_pos, ensure_ascii=False, separators=(",", ":"))
        + ";\n"
        "export const kabProv = (kab) => Object.keys(WILAYAH).find("
        "(p) => WILAYAH[p][kab]) || '';\n"
    )
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text(header + body, encoding="utf-8")
    print(f"Ditulis {OUTPUT} ({counts[3]} kelurahan, {OUTPUT.stat().st_size} bytes)")


if __name__ == "__main__":
    main()
